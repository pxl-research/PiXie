import logging
from services.database.database import get_db_connection
from typing import List, Optional, Dict, Any


logger = logging.getLogger(__name__)


def get_chat_history(
    user_id: int, session_id: str = "0", limit: Optional[int] = None
) -> List[Dict[str, str]]:
    """
    Retrieve chat history for a specific user from the database. Optionally limit the number of messages.

    Parameters:
        user_id (int): The ID of the user whose chat history is to be retrieved.
        session_id (str, optional): The session ID of the chat history. Defaults to "0".
        limit (Optional[int], optional): The maximum number of most recent messages to retrieve. Defaults to None.

    Returns:
        List[Dict[str, str]]: A list of dictionaries, where each dictionary contains the 'role' and 'content' of the user's messages.
    """
    conn = get_db_connection()
    try:
        logger.debug(
            f"Retrieving chat history - user_id: {user_id}, session_id: {session_id}, limit: {limit}"
        )
        with conn.cursor() as cursor:
            query = """
                SELECT role, content, timestamp
                FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                ORDER BY timestamp ASC
            """
            cursor.execute(query, (user_id, session_id))
            rows = cursor.fetchall()
            messages = []
            for role, content, _ in rows:
                messages.append({"role": role, "content": content})
            if limit is not None:
                messages = messages[-limit:]
            logger.info(
                f"Chat history retrieved - user_id: {user_id}, session_id: {session_id}, count: {len(messages)}"
            )
            return messages
    except Exception as e:
        logger.error(
            f"Error retrieving chat history - user_id: {user_id}, session_id: {session_id}: {e}",
            exc_info=True,
        )
        return []
    finally:
        conn.close()


def save_chat_history(
    user_id: int,
    question: Optional[str],
    response: Optional[str],
    session_id: str = "0",
) -> None:
    """
    Save a new interaction to the user's chat history in the database.

    Parameters:
        user_id (int): The ID of the user whose chat history is to be updated.
        question (str): The question or message provided by the user.
        response (str): The response generated by the AI.
        session_id (str, optional): The session ID of the chat history. Defaults to "0".

    Returns:
        None
    """
    conn = get_db_connection()
    try:
        logger.debug(
            f"Saving chat history - user_id: {user_id}, session_id: {session_id}, has_question: {question is not None}, has_response: {response is not None}"
        )
        with conn.cursor() as cursor:
            # Insert the user's question
            if question:
                cursor.execute(
                    """
                    INSERT INTO chat_messages (user_id, role, content, session_id)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (user_id, "user", question, session_id),
                )
                logger.debug(
                    f"User question saved - user_id: {user_id}, session_id: {session_id}"
                )
            # Insert the AI's response
            if response:
                cursor.execute(
                    """
                    INSERT INTO chat_messages (user_id, role, content, session_id)
                    VALUES (%s, %s, %s, %s)
                    """,
                    (user_id, "assistant", response, session_id),
                )
                logger.debug(
                    f"AI response saved - user_id: {user_id}, session_id: {session_id}"
                )
        conn.commit()
        logger.info(
            f"Chat history saved successfully - user_id: {user_id}, session_id: {session_id}"
        )
    except Exception as e:
        logger.error(
            f"Error saving chat history - user_id: {user_id}, session_id: {session_id}: {e}",
            exc_info=True,
        )
        conn.rollback()
        raise
    finally:
        conn.close()


def strip_sources(text: str) -> str:
    """
    Strip everything after the keyword 'Bronnen:' from the given text.

    In some cases, AI responses contain references to sources after the keyword 'Bronnen:'.
    This function removes all content after this keyword to keep the response focused.

    Parameters:
    - text: str
        The input text from which to remove sources.

    Returns:
    - str: The text with any content after 'Bronnen:' removed. If 'Bronnen:' is not found, the original text is returned, stripped of any leading or trailing whitespace.
    """
    try:
        if not isinstance(text, str):
            logger.warning(f"strip_sources received non-string input: {type(text)}")
            return ""

        keyword_position = text.find("Bronnen:")
        result = text[:keyword_position] if keyword_position != -1 else text
        logger.debug(
            f"Sources stripped - original_length: {len(text)}, result_length: {len(result)}, sources_found: {keyword_position != -1}"
        )
        return result
    except Exception as e:
        logger.error(f"Error stripping sources from text: {e}", exc_info=True)
        return text if isinstance(text, str) else ""


def format_chat_history_for_llm(chat_history):
    """
    Format the chat history for processing by a Language Learning Model (LLM).

    This function converts a list of user and AI messages into a structured format compatible with an LLM. It processes each message, adds the user's new message, and removes any sources from AI messages by calling `strip_sources`.

    Parameters:
    - chat_history: list
        A list of tuples, where each tuple contains:
          - str: The user's message
          - str or None: The AI's response, or None if there is no response yet.

    Returns:
    - list: A formatted list of dictionaries, where each dictionary contains:
          - 'role': str, specifying either 'user' or 'assistant'
          - 'content': str, containing the message content with sources removed for AI responses.
    """
    try:
        logger.debug(
            f"Formatting chat history for LLM - input_count: {len(chat_history) if chat_history else 0}"
        )
        formatted_history = [
            (
                message
                if message.get("role") == "user"
                else {
                    "role": message.get("role"),
                    "content": strip_sources(message.get("content")),
                }
            )
            for message in chat_history
        ]
        logger.debug(
            f"Chat history formatted for LLM - output_count: {len(formatted_history)}"
        )
        return formatted_history
    except Exception as e:
        logger.error(f"Error formatting chat history for LLM: {e}", exc_info=True)
        return []


def add_message_to_chat_history(
    chat_history: List[Dict[str, Any]],
    role: str,
    content: str,
    metadata: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, Any]]:
    """
    Add a new message to the chat history.

    Parameters:
    - chat_history: List[Dict[str, str]]
        The current chat history.
    - role: str
        The role of the message sender.
    - content: str
        The content of the message.

    Returns:
    - List[Dict[str, str]]: The updated chat history.
    """
    try:
        logger.debug(
            f"Adding message to chat history - role: {role}, content_length: {len(content) if content else 0}, has_metadata: {metadata is not None}"
        )
        if metadata is None:
            chat_history.append({"role": role, "content": content})
        else:
            chat_history.append(
                {"role": role, "content": content, "metadata": metadata}
            )
        logger.debug(
            f"Message added to chat history - total_messages: {len(chat_history)}"
        )
        return chat_history
    except Exception as e:
        logger.error(
            f"Error adding message to chat history - role: {role}: {e}", exc_info=True
        )
        return chat_history


def replace_last_message_in_chat_history(
    chat_history: List[Dict[str, str]],
    role: str,
    content: str,
    metadata: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, str]]:
    """
    Replace the last message in the chat history with a new message.

    Parameters:
    - chat_history: List[Dict[str, str]]
        The current chat history.
    - role: str
        The role of the message sender.
    - content: str
        The content of the message.

    Returns:
    - List[Dict[str, str]]: The updated chat history.
    """
    try:
        logger.debug(
            f"Replacing last message in chat history - role: {role}, content_length: {len(content) if content else 0}, has_metadata: {metadata is not None}"
        )
        new_message: dict[str, Any] = {"role": role, "content": content}
        if metadata is not None:
            new_message["metadata"] = metadata

        if chat_history and chat_history[-1]["role"] == role:
            chat_history[-1] = new_message
            logger.debug("Last message replaced in chat history")
        else:
            chat_history.append(new_message)
            logger.debug("New message appended to chat history")
        logger.debug(f"Chat history updated - total_messages: {len(chat_history)}")
        return chat_history
    except Exception as e:
        logger.error(
            f"Error replacing last message in chat history - role: {role}: {e}",
            exc_info=True,
        )
        return chat_history


def delete_chat_history(user_id: str, session_id: str = "0"):
    """
    Delete the chat history for a specific user from the database.

    Parameters:
    - user_id: str
        The ID of the user whose chat history is to be deleted.
    - session_id: str, optional
        The session ID of the chat history to delete. Defaults to "0".

    Returns:
    - None
    """
    conn = get_db_connection()
    try:
        logger.debug(
            f"Deleting chat history - user_id: {user_id}, session_id: {session_id}"
        )
        with conn.cursor() as cursor:
            cursor.execute(
                """
                DELETE FROM chat_messages
                WHERE user_id = %s AND session_id = %s
                """,
                (user_id, session_id),
            )
        conn.commit()
        logger.info(
            f"Chat history deleted successfully - user_id: {user_id}, session_id: {session_id}"
        )
    except Exception as e:
        logger.error(
            f"Error deleting chat history - user_id: {user_id}, session_id: {session_id}: {e}",
            exc_info=True,
        )
        conn.rollback()
        raise
    finally:
        conn.close()
